export function getFlagUrl(currencyCode) {
  const countryCode = CURRENCY_TO_COUNTRY[currencyCode];
  if (!countryCode) return null;
  return `https://flagcdn.com/w40/${countryCode.toLowerCase()}.png`;
}

export function getFlagSvgUrl(currencyCode) {
  const countryCode = CURRENCY_TO_COUNTRY[currencyCode];
  if (!countryCode) return null;
  return `https://flagcdn.com/${countryCode.toLowerCase()}.svg`;
}

export function hasFlag(currencyCode) {
  return currencyCode in CURRENCY_TO_COUNTRY;
}